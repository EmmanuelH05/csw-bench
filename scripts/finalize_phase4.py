"""Everything between "the full-set runs finished" and "the docs carry their numbers",
with nothing transcribed by hand.

Writes `docs/results.md`, rewrites the README's headline block from the same `Report`
objects, and prints the digest of numbers the PENDING RUNS sections of
`docs/findings.md` and `docs/limitations.md` ask for. Interpretation stays manual; only
the arithmetic moves here, because a number retyped from one file into another is a
number `csw-bench table` can no longer reproduce -- and Phase 5 requires every number to
come back from committed code and data.

The two numbers that already have a command of their own -- the prompt-sensitivity delta
(`csw-bench report --compare`) and the continuation violation-production rate
(`scripts/continuation_escape_hatch.py`) -- are pointed at, not recomputed.

Usage: uv run python scripts/finalize_phase4.py runs/full-qwen3-30b-a \
           runs/full-gpt-oss-20b-a runs/full-deepseek-r1-32b-a [--check]
"""

from __future__ import annotations

import argparse
import re
from collections import Counter, defaultdict
from dataclasses import replace
from pathlib import Path

from csw_bench.loader import load_items
from csw_bench.prompts import render
from csw_bench.results import (
    Cell,
    Report,
    format_markdown_table,
    load_run,
    summarize,
)
from csw_bench.runner import RunResult
from csw_bench.taxonomy import TaskType, ViolationType

REPO = Path(__file__).resolve().parents[1]
ITEMS = REPO / "data" / "items"
RESULTS = REPO / "docs" / "results.md"
README = REPO / "README.md"
VERSIONS = REPO / "docs" / "versions.md"

HEADLINE_START = "<!-- headline-table:start -->"
HEADLINE_END = "<!-- headline-table:end -->"

CellIndex = dict[tuple[TaskType, ViolationType | None], Cell]


def recorded_v1_hash() -> str:
    """The hash `matriz` records against, read from the row `tests/test_shipped_set.py`
    pins the items on disk to.
    """
    text = VERSIONS.read_text(encoding="utf-8")
    rows = [line for line in text.splitlines() if line.startswith("| v1.0 ")]
    if len(rows) != 1:
        raise SystemExit(f"{VERSIONS} must carry exactly one v1.0 row; found {len(rows)}")
    match = re.search(r"\b[0-9a-f]{64}\b", rows[0])
    if match is None:
        raise SystemExit(f"{VERSIONS}: the v1.0 row carries no SHA-256")
    return match.group()


def _table_command(run_dirs: list[Path]) -> str:
    return "uv run csw-bench table " + " ".join(str(d) for d in run_dirs)


def _stimulus_multiplicity(template_id: str) -> list[str]:
    """Cells where several items render to the same prompt. At temperature 0 those items
    share one response between them, so the cell's n overstates its independent
    observations -- found 2026-09-08 when the full qwen3 run served never-run Phase 4
    continuation items from cache. Stated next to the table, not corrected in it: n is
    still the number of scored records.
    """
    by_cell: dict[tuple[TaskType, ViolationType], list[str]] = defaultdict(list)
    for item in load_items(ITEMS):
        by_cell[(item.task_type, item.primary_violation)].append(render(item, template_id))
    return [
        f"- {task.value} / {violation.value}: {len(prompts)} items, "
        f"{len(set(prompts))} distinct prompts"
        for (task, violation), prompts in sorted(by_cell.items())
        if len(set(prompts)) < len(prompts)
    ]


def _results_document(
    run_dirs: list[Path],
    reports: list[tuple[str, Report]],
    item_hash: str,
    items: int,
    template_id: str,
) -> str:
    names = ", ".join(f"`{d.name}`" for d in run_dirs)
    document = (
        f"# Results, full set ({items} items)\n\n"
        f"Generated by `{_table_command(run_dirs)}`; this file is written by "
        "`scripts/finalize_phase4.py`, and the table below is that command's output "
        "unchanged. Pilot-scale table: `docs/results-pilot.md`. Read `ml_identification` "
        "and `constrained_continuation` through the caveats in `docs/findings.md`.\n\n"
        f"Item set `{item_hash}`; runs: {names}.\n\n"
        f"{format_markdown_table(reports)}\n"
    )
    multiplicity = _stimulus_multiplicity(template_id)
    if multiplicity:
        document += (
            "\n**Stimulus multiplicity.** In the cells below, several items render to the "
            "same prompt; at temperature 0 they share one model response, so n counts scored "
            "records, not independent observations, and a response can match at most one "
            "sibling's gold string (`docs/limitations.md`, \"Known item-set defects at "
            'v1.0").\n\n' + "\n".join(multiplicity) + "\n"
        )
    return document


def _headline_block(reports: list[tuple[str, Report]], run_dirs: list[Path], items: int) -> str:
    pooled = [(label, replace(report, cells=report.task_rows())) for label, report in reports]
    return (
        f"{HEADLINE_START}\n"
        f"**Headline table ({items} items, {len(reports)} models).** The pooled per-task rows of "
        "`docs/results.md`; the per-violation rows are in that file. Regenerate with "
        f"`{_table_command(run_dirs)}`.\n\n"
        f"{format_markdown_table(pooled)}\n"
        f"{HEADLINE_END}"
    )


def replace_block(text: str, block: str) -> str:
    start = text.find(HEADLINE_START)
    end = text.find(HEADLINE_END)
    if start == -1 or end < start:
        raise SystemExit(
            f"{README} has no {HEADLINE_START} / {HEADLINE_END} pair to write between; "
            "restore the markers around the Results section's headline paragraph"
        )
    return text[:start] + block + text[end + len(HEADLINE_END) :]


def _verdict(cell: Cell) -> str:
    """Whether the pooled interval clears the task's own chance floor. `above_chance`
    already subtracts the floor, so the test is against zero.
    """
    if cell.ci_low > 0:
        standing = "ABOVE"
    elif cell.ci_high < 0:
        standing = "BELOW"
    else:
        standing = "indistinguishable from"
    return (
        f"{standing} chance ({cell.mean_above_chance:+.3f} "
        f"[{cell.ci_low:+.3f}, {cell.ci_high:+.3f}], n={cell.n})"
    )


def _headline_section(runs: list[tuple[str, CellIndex]]) -> list[str]:
    lines = [
        "## docs/findings.md, 'Headline result'",
        "Per task: which models sit above chance with an interval that excludes zero.",
    ]
    for task in TaskType:
        lines.append(f"\n{task.value}")
        for label, cells in runs:
            cell = cells.get((task, None))
            state = _verdict(cell) if cell is not None and cell.n else "no scored items"
            lines.append(f"  {label}: {state}")
    return lines


def _clustering_section(runs: list[tuple[str, CellIndex]]) -> list[str]:
    lines = [
        "\n## docs/findings.md, 'Error patterns by violation type'",
        "Spread is max - min of the above-chance means across T1/T3/T5 within a task. A "
        "large spread whose per-violation intervals do not overlap is clustering, which "
        "implies a represented constraint; a small one is not. The intervals themselves "
        "are the per-violation rows of docs/results.md.",
    ]
    for task in TaskType:
        lines.append(f"\n{task.value}")
        for label, cells in runs:
            scored = ((v, cells.get((task, v))) for v in ViolationType)
            means = {v.value: c.mean_above_chance for v, c in scored if c is not None and c.n}
            if not means:
                lines.append(f"  {label}: no scored items")
                continue
            detail = ", ".join(f"{name} {value:+.3f}" for name, value in means.items())
            lines.append(
                f"  {label}: spread {max(means.values()) - min(means.values()):.3f}  ({detail})"
            )
    return lines


def _error_section(labelled: list[tuple[str, RunResult]]) -> list[str]:
    lines = [
        "\n## docs/limitations.md, PENDING RUNS -- provider-error rate",
        "Errored records are provider failures, not model answers: excluded from every "
        "score above, counted here. Whether deepseek-r1:32b's ml_identification timeouts "
        "and gpt-oss:20b's continuation budget exhaustion held at 402 items is read off "
        "these rows.",
    ]
    for label, result in labelled:
        totals: Counter[TaskType] = Counter()
        errors: Counter[TaskType] = Counter()
        for record in result.records:
            totals[record.task_type] += 1
            if record.errored:
                errors[record.task_type] += 1
        lines.append(f"\n{label}: {sum(errors.values())}/{sum(totals.values())} overall")
        for task in TaskType:
            if not totals[task]:
                continue
            lines.append(
                f"  {task.value:<26} {errors[task]:>4}/{totals[task]:<5} "
                f"{errors[task] / totals[task]:>6.1%}"
            )
    return lines


def _digest(reports: list[tuple[str, Report]], results: list[RunResult]) -> str:
    runs: list[tuple[str, CellIndex]] = [
        (label, {(c.task_type, c.violation): c for c in report.cells}) for label, report in reports
    ]
    labelled = [(label, result) for (label, _), result in zip(reports, results, strict=True)]
    lines = [
        *_headline_section(runs),
        *_clustering_section(runs),
        *_error_section(labelled),
        "\n## docs/limitations.md, PENDING RUNS -- the two numbers another command owns",
        "Not recomputed here, because each already has a command that produces it and "
        "run_phase4.sh runs both:",
        "  violation-production rate   scripts/continuation_escape_hatch.py "
        "-> runs/logs/escape-hatch.txt",
        "  prompt-sensitivity delta    csw-bench report --compare "
        "-> runs/logs/prompt-sensitivity.txt",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("run_dirs", type=Path, nargs="+")
    parser.add_argument("--resamples", type=int, default=10_000)
    parser.add_argument("--ci-seed", type=int, default=0)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Compute and print everything, write nothing. Reads the digest without the "
        "docs changing underneath it.",
    )
    args = parser.parse_args()

    run_dirs: list[Path] = list(args.run_dirs)
    results = [load_run(run_dir) for run_dir in run_dirs]
    hashes = {r.item_set_hash for r in results}
    if len(hashes) != 1:
        raise SystemExit(
            "runs evaluated different item sets "
            f"({', '.join(sorted(h[:12] for h in hashes))}); their scores are not comparable"
        )
    item_hash = hashes.pop()
    expected = recorded_v1_hash()
    if item_hash != expected:
        mismatch = (
            f"the runs evaluated item set {item_hash[:12]}, but docs/versions.md records "
            f"{expected[:12]} as v1.0"
        )
        # Fatal only when about to write. --check over the pilot runs is how this script
        # gets exercised at all before the full runs exist, and a day and a half of
        # inference is the wrong time to discover a formatting bug here.
        if not args.check:
            raise SystemExit(
                f"{mismatch}. Publishing a headline table under a hash the version table "
                "does not name is what that table exists to prevent."
            )
        print(f"WARNING: {mismatch}; --check, so this is a dry run over another item set.\n")

    labels = [result.config.model for result in results]
    if len(set(labels)) != len(labels):
        raise SystemExit(f"two runs share a model id ({labels}); pass one run per model")
    reports = [
        (label, summarize(r.records, resamples=args.resamples, seed=args.ci_seed))
        for label, r in zip(labels, results, strict=True)
    ]

    evaluated = {len(r.records) for r in results}
    if len(evaluated) != 1:
        raise SystemExit(
            f"the runs cover different numbers of items ({sorted(evaluated)}) despite "
            "sharing an item-set hash; one of them did not finish"
        )
    items = evaluated.pop()

    template_ids = {r.config.template_id for r in results}
    if len(template_ids) != 1:
        raise SystemExit(
            f"runs used different templates ({sorted(template_ids)}); pass one template"
        )
    document = _results_document(run_dirs, reports, item_hash, items, template_ids.pop())
    readme = replace_block(
        README.read_text(encoding="utf-8"), _headline_block(reports, run_dirs, items)
    )

    print(_digest(reports, results))

    if args.check:
        print(f"\n--check: nothing written; {RESULTS.name} and {README.name} are untouched.")
        return 0

    RESULTS.write_text(document, encoding="utf-8")
    README.write_text(readme, encoding="utf-8")
    print(f"\nwrote docs/{RESULTS.name} and the headline block of {README.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
